/** Arma un link de WhatsApp con mensaje pre-cargado (funciona en móvil y escritorio). */
export function whatsappLink(e164 = site.whatsappNumbers[0].e164, message = defaultWhatsappMessage()) {
  return `https://wa.me/${e164}?text=${encodeURIComponent(message)}`;
}

export function defaultWhatsappMessage() {
  return `Hola ${site.name}. Quiero información sobre sus propiedades y servicios de asesoría.`;
}

export function propertyWhatsappMessage(title) {
  return `Hola ${site.name}. Vi la propiedad "${title}" en su sitio web y me gustaría más información.`;
}

/** Link de Google Maps para abrir la app nativa en el teléfono o Maps web en escritorio. */
export function mapsLink(query = site.mapsQuery) {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`;
}

export function mapsEmbedSrc(query = site.mapsQuery) {
  return `https://www.google.com/maps?q=${encodeURIComponent(query)}&output=embed`;
}

export function telLink(e164 = site.phoneE164) {
  return `tel:${e164.replace(/\s+/g, '')}`;
}

export function mailLink(subject = '') {
  return subject ? `mailto:${site.email}?subject=${encodeURIComponent(subject)}` : `mailto:${site.email}`;
}
